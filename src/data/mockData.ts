export function getBookById(id: string): Book | undefined {
  return mockBooks.find((b) => b.id === id);
}

export function getFeaturedBooks(): Book[] {
  return mockBooks.filter((b) => b.rating >= 4.5).slice(0, 4);
}

export function getNewArrivals(): Book[] {
  return [...mockBooks]
    .sort((a, b) => new Date(b.addedDate).getTime() - new Date(a.addedDate).getTime())
    .slice(0, 4);
}

export function getRelatedBooks(book: Book, limit = 4): Book[] {
  return mockBooks
    .filter((b) => b.id !== book.id && (b.category === book.category || b.tags.some((t) => book.tags.includes(t))))
    .slice(0, limit);
}
